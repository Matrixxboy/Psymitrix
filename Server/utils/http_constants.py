from enum import IntEnum
from fastapi import status

class HTTP_STATUS(IntEnum):
    OK = status.HTTP_200_OK
    CREATED = status.HTTP_201_CREATED
    BAD_REQUEST = status.HTTP_400_BAD_REQUEST
    UNAUTHORIZED = status.HTTP_401_UNAUTHORIZED
    FORBIDDEN = status.HTTP_403_FORBIDDEN
    NOT_FOUND = status.HTTP_404_NOT_FOUND
    CONFLICT = status.HTTP_409_CONFLICT
    INTERNAL_SERVER_ERROR = status.HTTP_500_INTERNAL_SERVER_ERROR
    TOO_MANY_REQUESTS = status.HTTP_429_TOO_MANY_REQUESTS
    ERROR = status.HTTP_501_NOT_IMPLEMENTED
    VALIDATION = status.HTTP_422_UNPROCESSABLE_CONTENT
    EMAILVERIFICATION = status.HTTP_428_PRECONDITION_REQUIRED       # Email not verified yet
    INVALID_COUPON = status.HTTP_400_BAD_REQUEST                    # Bad input or expired coupon
    DATA_EXIST = status.HTTP_409_CONFLICT                           # Data already exists in DB
    USER_ALREADY_EXISTS = status.HTTP_409_CONFLICT                  # Same as DATA_EXIST, user conflict
    USERNAME_ALREADY_EXISTS = status.HTTP_409_CONFLICT              # Same idea, username conflict
    DATABASE_CONNECTION_FAILED = status.HTTP_503_SERVICE_UNAVAILABLE
    SERVICE_UNAVAILABLE = status.HTTP_503_SERVICE_UNAVAILABLE
    
